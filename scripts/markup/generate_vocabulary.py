"""Generate fast membership matches and enumerable names from one reviewed table."""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "scripts/markup/vocabulary.json"
OUTPUT = ROOT / "package/MarkupNameTables.roc"
TABLES = ("html", "svg", "mathml", "aria")


def load(path: Path = SOURCE) -> dict[str, list[str]]:
    document = json.loads(path.read_text())
    if document.get("schema_version") != 1 or set(document.get("tables", {})) != set(TABLES):
        raise ValueError("expected schema_version 1 and HTML/SVG/MathML/ARIA tables")
    tables = document["tables"]
    for name, values in tables.items():
        if not isinstance(values, list) or not values:
            raise ValueError(f"{name}: expected a nonempty list")
        if not all(isinstance(value, str) and re.fullmatch(r"[A-Za-z][A-Za-z0-9-]*", value) for value in values):
            raise ValueError(f"{name}: names must be canonical ASCII element/attribute spellings")
        if values != sorted(set(values)):
            raise ValueError(f"{name}: names must be unique and sorted by ASCII spelling")
    return tables


def render(tables: dict[str, list[str]]) -> str:
    lines = [
        "# Generated by scripts/markup/generate_vocabulary.py from scripts/markup/vocabulary.json.",
        "# Edit that canonical table and regenerate; membership stays a match expression.",
        "MarkupNameTables :: [].{",
    ]
    for table in TABLES:
        names = tables[table]
        values = ", ".join(json.dumps(name) for name in names)
        alternatives = " | ".join(json.dumps(name) for name in names)
        lines.extend([
            f"\t{table}_names : List(Str)",
            f"\t{table}_names = [{values}]",
            f"\t{table}_name : Str -> Bool",
            f"\t{table}_name = |name| match name {{",
            f"\t\t{alternatives} => True",
            "\t\t_ => False",
            "\t}",
        ])
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="refuse stale generated Roc source")
    args = parser.parse_args()
    expected = render(load())
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            parser.error("MarkupNameTables.roc is stale; run python3 scripts/markup/generate_vocabulary.py")
    else:
        OUTPUT.write_text(expected)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
